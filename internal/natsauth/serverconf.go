package natsauth

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"text/template"
)

// Files and directories under the NATS dir.
const (
	ConfFile        = "nats-server.conf"
	OperatorJWTFile = "operator.jwt"
	ResolverDir     = "jwt"
	JetStreamDir    = "js"
)

// Defaults match "Deployment on library" in docs/ARCHITECTURE.md.
const (
	DefaultClientListen  = "127.0.0.1:4222"
	DefaultWSListen      = "127.0.0.1:7810" // reached as wss://…/nats through the Cloudflare tunnel
	DefaultMonitorListen = "127.0.0.1:8222"
	DefaultMaxFileStore  = 64 * AccountDiskQuota // room for 64 client accounts; see AccountDiskQuota
	DefaultMaxMemStore   = 64 << 20

	// MaxPayload must hold a 2 MiB read after JSON escaping.
	MaxPayload = 8 << 20
)

// ServerConfig describes the nats-server files that init writes. Dir is the
// NATS dir as nats-server sees it; every path in the config is under it.
type ServerConfig struct {
	Dir           string // absolute
	ClientListen  string // host:port; DefaultClientListen if empty
	WSListen      string // host:port; DefaultWSListen if empty
	MonitorListen string // host:port; DefaultMonitorListen if empty
	MaxFileStore  int64  // JetStream file storage across all accounts; DefaultMaxFileStore if 0
	MaxMemStore   int64  // DefaultMaxMemStore if 0
}

func (c ServerConfig) withDefaults() ServerConfig {
	if c.ClientListen == "" {
		c.ClientListen = DefaultClientListen
	}
	if c.WSListen == "" {
		c.WSListen = DefaultWSListen
	}
	if c.MonitorListen == "" {
		c.MonitorListen = DefaultMonitorListen
	}
	if c.MaxFileStore == 0 {
		c.MaxFileStore = DefaultMaxFileStore
	}
	if c.MaxMemStore == 0 {
		c.MaxMemStore = DefaultMaxMemStore
	}
	return c
}

var confTemplate = template.Must(template.New("conf").Funcs(template.FuncMap{"q": strconv.Quote}).Parse(`# Generated by keyhole-relay init. Operator mode: every client is its own
# account, pushed to the full resolver by the relay over the SYS account.
server_name: "keyhole"
listen: {{q .ClientListen}}
http: {{q .MonitorListen}}
max_payload: {{.MaxPayload}}

operator: {{q .OperatorJWT}}
system_account: {{q .SysAccount}}
resolver: {
  type: full
  dir: {{q .ResolverDir}}
  allow_delete: false
  interval: "2m"
}
resolver_preload: {
  {{.SysAccount}}: {{q .SysAccountJWT}}
}

jetstream: {
  store_dir: {{q .JetStreamDir}}
  max_memory_store: {{.MaxMemStore}}
  max_file_store: {{.MaxFileStore}}
}

# TLS is terminated by Cloudflare in front of this listener.
websocket: {
  listen: {{q .WSListen}}
  no_tls: true
  compression: true
}
`))

// ServerConf renders nats-server.conf for this operator.
func (o *Operator) ServerConf(c ServerConfig) ([]byte, error) {
	if !filepath.IsAbs(c.Dir) {
		return nil, fmt.Errorf("natsauth: nats dir %q must be absolute", c.Dir)
	}
	if strings.ContainsFunc(c.Dir, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
		return nil, errors.New("natsauth: nats dir contains control characters")
	}
	c = c.withDefaults()
	data := map[string]any{
		"ClientListen":  c.ClientListen,
		"MonitorListen": c.MonitorListen,
		"WSListen":      c.WSListen,
		"MaxPayload":    MaxPayload,
		"OperatorJWT":   filepath.Join(c.Dir, OperatorJWTFile),
		"SysAccount":    o.SysAccount,
		"SysAccountJWT": o.SysAccountJWT,
		"ResolverDir":   filepath.Join(c.Dir, ResolverDir),
		"JetStreamDir":  filepath.Join(c.Dir, JetStreamDir),
		"MaxMemStore":   c.MaxMemStore,
		"MaxFileStore":  c.MaxFileStore,
	}
	var buf bytes.Buffer
	if err := confTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("natsauth: render %s: %w", ConfFile, err)
	}
	return buf.Bytes(), nil
}

// WriteServerDir writes nats-server.conf and operator.jwt into c.Dir and
// creates the empty resolver and JetStream directories. The SYS account
// reaches the resolver through resolver_preload; client accounts are pushed
// by the relay. Existing files are not replaced.
func WriteServerDir(o *Operator, c ServerConfig) error {
	conf, err := o.ServerConf(c)
	if err != nil {
		return err
	}
	for _, d := range []string{c.Dir, filepath.Join(c.Dir, ResolverDir), filepath.Join(c.Dir, JetStreamDir)} {
		if err := os.MkdirAll(d, 0o700); err != nil {
			return fmt.Errorf("natsauth: %w", err)
		}
	}
	if err := writeNewFile(filepath.Join(c.Dir, OperatorJWTFile), []byte(o.JWT+"\n")); err != nil {
		return err
	}
	return writeNewFile(filepath.Join(c.Dir, ConfFile), conf)
}
